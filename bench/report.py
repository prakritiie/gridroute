"""Benchmark report: bench/results/{micro,k6}.json -> docs/benchmarks.md + docs/bench_p99.svg

    python -m bench.report

The chart follows the dataviz method: one axis, 2 px lines, 8 px markers, legend + direct labels, the first
three categorical slots (validated all-pairs for CVD in light and dark), and its own light/dark steps.
"""
from __future__ import annotations

import json
import math
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
RES = Path(__file__).parent / "results"
DOCS = ROOT / "docs"
LABEL = {"h3": "H3 rings (GridRoute)", "geo": "Redis GEOSEARCH", "postgis": "PostGIS KNN + GiST"}
SLOT = {"h3": 1, "geo": 2, "postgis": 3}


def svg_chart(micro: dict, metric: str = "p99_ms") -> str:
    sizes = sorted(micro["sizes"], key=int)
    backends = list(LABEL)
    vals = [micro["sizes"][s][b][metric] for s in sizes for b in backends if b in micro["sizes"][s]]
    W, H, L, R, T, B = 720, 360, 64, 190, 28, 52
    lo, hi = math.log10(min(vals) * 0.7), math.log10(max(vals) * 1.4)
    x = lambda i: L + i * (W - L - R) / max(1, len(sizes) - 1)  # noqa: E731
    y = lambda v: T + (hi - math.log10(v)) / (hi - lo) * (H - T - B)  # noqa: E731
    ticks = [t for e in range(math.floor(lo), math.ceil(hi) + 1) for t in (10 ** e, 2 * 10 ** e, 5 * 10 ** e)
             if lo <= math.log10(t) <= hi]
    parts = [f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 {W} {H}" font-family="system-ui, -apple-system, Segoe UI, sans-serif">',
             """<style>
  .bg{fill:#fcfcfb}.grid{stroke:#e1e0d9}.axis{stroke:#c3c2b7}.t1{fill:#0b0b0b}.t2{fill:#52514e}.t3{fill:#898781}
  .s1{stroke:#2a78d6;fill:#2a78d6}.s2{stroke:#eb6834;fill:#eb6834}.s3{stroke:#1baf7a;fill:#1baf7a}.ring{stroke:#fcfcfb}.ln{fill:none}
  @media (prefers-color-scheme: dark){
    .bg{fill:#1a1a19}.grid{stroke:#2c2c2a}.axis{stroke:#383835}.t1{fill:#ffffff}.t2{fill:#c3c2b7}.t3{fill:#898781}
    .s1{stroke:#3987e5;fill:#3987e5}.s2{stroke:#d95926;fill:#d95926}.s3{stroke:#199e70;fill:#199e70}.ring{stroke:#1a1a19}.ln{fill:none}}
</style>""",
             f'<rect class="bg" width="{W}" height="{H}" rx="8"/>',
             f'<text class="t1" x="{L}" y="18" font-size="13" font-weight="600">Nearby lookup, p99 latency (ms, log scale), lower is better</text>']
    for t in ticks:
        parts.append(f'<line class="grid" x1="{L}" x2="{W - R}" y1="{y(t):.1f}" y2="{y(t):.1f}" stroke-width="1"/>')
        parts.append(f'<text class="t3" x="{L - 8}" y="{y(t) + 4:.1f}" font-size="11" text-anchor="end">{t:g}</text>')
    parts.append(f'<line class="axis" x1="{L}" x2="{W - R}" y1="{H - B}" y2="{H - B}" stroke-width="1"/>')
    for i, s in enumerate(sizes):
        parts.append(f'<text class="t3" x="{x(i):.1f}" y="{H - B + 18}" font-size="11" text-anchor="middle">{int(s):,} drivers</text>')
    for b in backends:
        pts = [(x(i), y(micro["sizes"][s][b][metric])) for i, s in enumerate(sizes) if b in micro["sizes"][s]]
        if not pts:
            continue
        k = SLOT[b]
        parts.append(f'<polyline class="s{k} ln" stroke-width="2" stroke-linejoin="round" '
                     f'points="{" ".join(f"{px:.1f},{py:.1f}" for px, py in pts)}"/>')
        for px, py in pts:     # series fill from .sN, 2 px surface ring from .ring (declared later, so it wins)
            parts.append(f'<circle class="s{k} ring" cx="{px:.1f}" cy="{py:.1f}" r="5" stroke-width="2"/>')
        last = micro["sizes"][sizes[-1]][b][metric]
        parts.append(f'<text class="t2" x="{pts[-1][0] + 10:.1f}" y="{pts[-1][1] + 4:.1f}" font-size="12">'
                     f'{LABEL[b]} · {last:.2f} ms</text>')
    # legend (always present for >= 2 series)
    for j, b in enumerate(backends):
        lx = L + j * 190
        parts.append(f'<line class="s{SLOT[b]}" x1="{lx}" x2="{lx + 18}" y1="{H - 12}" y2="{H - 12}" stroke-width="2"/>')
        parts.append(f'<text class="t2" x="{lx + 24}" y="{H - 8}" font-size="11">{LABEL[b]}</text>')
    parts.append("</svg>")
    return "\n".join(parts)


def main() -> None:
    micro = json.loads((RES / "micro.json").read_text())
    k6 = json.loads((RES / "k6.json").read_text()) if (RES / "k6.json").exists() else None
    (DOCS / "bench_p99.svg").write_text(svg_chart(micro), encoding="utf-8", newline="\n")

    lines = ["# Benchmarks: nearby lookup at 1k → 100k drivers (claim C5)", "",
             "_Generated by `python -m bench.report` from `bench/results/`. Do not edit by hand._", "",
             "**Question.** The 5 nearest drivers within 1 km of a point. **Data.** Driver positions and query points "
             "are real June 2016 pickup locations (Manhattan-dense, like the live service), same seed for every "
             "backend. **Correctness.** Every answer is scored against an exact brute-force top-5 (recall@5).", "",
             "![p99 latency by fleet size](bench_p99.svg)", "",
             "## Direct (client → backend, no HTTP)", "",
             f"{micro['queries']:,} queries per cell, one Python client on the same machine as the servers.", "",
             "| Drivers | Backend | p50 | p99 | Recall@5 | Position writes / s |",
             "|---|---|---|---|---|---|"]
    for s in sorted(micro["sizes"], key=int):
        for b in LABEL:
            r = micro["sizes"][s].get(b)
            if r:
                lines.append(f"| {int(s):,} | {LABEL[b]} | {r['p50_ms']:.3f} ms | {r['p99_ms']:.3f} ms | "
                             f"{r['recall_at_5']:.4f} | {r['writes_per_s']:,.0f} |")
    if k6:
        lines += ["", "## Under load (k6, constant arrival rate)", "",
                  f"{k6['rate']} requests/s for {k6['duration']} per cell through one identical FastAPI endpoint "
                  "(`bench/api.py`, 4 workers), so the HTTP cost is the same for every backend.", "",
                  "| Drivers | Backend | p50 | p90 | p99 | Achieved req/s | Failed |", "|---|---|---|---|---|---|---|"]
        for s in sorted(k6["sizes"], key=int):
            for b in LABEL:
                r = k6["sizes"][s].get(b)
                if r:
                    lines.append(f"| {int(s):,} | {LABEL[b]} | {r['p50_ms']:.2f} ms | {r['p90_ms']:.2f} ms | "
                                 f"{r['p99_ms']:.2f} ms | {r['rps']:.0f} | {r['failed_pct']:.2f}% |")
    lines += ["", "## What the benchmark changed", "",
              "The first run had the H3 search making one Redis round trip per ring and ranking every candidate "
              "in Python: **2.7 ms p50 at 1k drivers, 21 ms at 100k**. Two changes, both kept exact by the C3 "
              "brute-force property test (0/500 wrong):",
              "1. **One round trip.** The ring walk moved into `ring_search.lua`.",
              "2. **Best-first with a distance bound.** At Manhattan density one res-9 cell holds ~150 drivers, and "
              "the k+1 ring guard made every query touch ~1,000 of them. The script now visits cells in order of a "
              "lower bound on their distance (centre distance − 220 m, the measured max res-9 circumradius in NYC) "
              "and stops when no remaining cell can beat the 5th driver found. This is exact within the rings, "
              "where the guard was a heuristic.",
              "Result: **0.86 ms at 1k, 1.5 ms at 10k, 4.6 ms at 100k** (4.6× faster at 100k), now ahead of "
              "Redis GEO at 100k.", "",
              "## What it didn't change", "",
              "- **PostGIS wins pure lookup at high density.** Its KNN walk over the GiST index touches a handful "
              "of entries; the H3 search still reads every fresh driver in the cells it can't rule out.",
              "- **One Redis tops out around 200 lookups/s at 100k Manhattan-dense drivers** (k6 above): Redis "
              "runs commands on one thread and each lookup costs ~4–6 ms of its CPU at that density. Redis GEO "
              "saturates the same way; PostGIS spreads queries over cores. The live matcher needs a few lookups "
              "per second (real NYC peak is ~7 requests/s), so this is headroom, not a bottleneck, but it is "
              "the ceiling. The upgrade path is the spec's: shard Redis by area (H3 parent cell), or index the "
              "densest areas at res 10.",
              "- **Why keep H3 then?** Writes are the hot path (every driver, every 4 s), and H3 is the fastest "
              "writer here while doing the most per write; positions, status, leases and freshness change "
              "atomically in one place; and the cell IDs are the aggregation keys for the heatmap, the demand "
              "history and the forecaster.", "",
              "## Reading this fairly", "",
              "- **Writes are not like for like.** A GridRoute position write is `move_driver.lua`: sequence check "
              "(drops late pings), status check, cell move, freshness score and driver hash, atomically. "
              "`GEOADD` only moves a point, and PostGIS gets its idiomatic bulk path (COPY + one UPDATE).",
              "- **Freshness.** H3 and PostGIS filter by last-ping time in the query; Redis GEO has no notion of "
              "freshness (silent drivers need a separate cleanup), which favours it here.",
              "- **One laptop.** Servers, client and load generator share one machine (12 cores, Docker on Windows). "
              "Absolute numbers are lower bounds on a real deployment; the comparison is the point.", ""]
    (DOCS / "benchmarks.md").write_text("\n".join(lines), encoding="utf-8", newline="\n")
    print("wrote docs/benchmarks.md, docs/bench_p99.svg")


if __name__ == "__main__":
    main()
