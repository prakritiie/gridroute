"""Evaluate an ETA model against B1-B3 on held-out June trips (spec §8.1), by slice; write metrics + model card.

    python -m ml.evaluate                 # latest models/eta/vN
    python -m ml.evaluate --version v1

Gate (spec §13 week 6): the model beats B2 and B3 on MAE overall and on the < 3 km slice (pickup-like legs).
Writes models/eta/vN/{metrics.json, card.md} and docs/model_card_eta.md.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import lightgbm as lgb
import numpy as np

from core import features
from ml.baselines import Baselines
from ml.eta_train import MODELS, load, matrix

ROOT = Path(__file__).resolve().parent.parent
# rough Manhattan polygon (lat, lng), same as the data card's
MANHATTAN = [(40.6996, -74.0204), (40.7516, -74.0134), (40.8789, -73.9318), (40.8776, -73.9103),
             (40.7980, -73.9283), (40.7096, -73.9718)]


def in_polygon(lat: np.ndarray, lng: np.ndarray, poly=MANHATTAN) -> np.ndarray:
    inside = np.zeros(len(lat), dtype=bool)
    j = len(poly) - 1
    for i in range(len(poly)):
        yi, xi = poly[i]
        yj, xj = poly[j]
        cross = ((yi > lat) != (yj > lat)) & (lng < (xj - xi) * (lat - yi) / (yj - yi + 1e-12) + xi)
        inside ^= cross
        j = i
    return inside


def scores(y: np.ndarray, p: np.ndarray) -> dict:
    p = np.maximum(p, 1.0)
    err = np.abs(p - y)
    return {"mae_s": float(err.mean()), "mape": float(np.mean(err / y)), "p90_abs_s": float(np.percentile(err, 90)),
            "rmsle": float(np.sqrt(np.mean((np.log1p(p) - np.log1p(y)) ** 2)))}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--version")
    a = ap.parse_args()
    vdir = MODELS / a.version if a.version else max(MODELS.glob("v*"), key=lambda p: int(p.name[1:]))
    info = json.loads((vdir / "train.json").read_text())
    vocab = features.Vocab.load(vdir / "vocab.json")
    base = Baselines.load(vdir / "baselines.json")
    model = lgb.Booster(model_file=str(vdir / "model.txt"))

    te = load("test")
    X = matrix(te, vocab)
    fi = {f: i for i, f in enumerate(features.FEATURES)}
    y = te["duration_s"].astype(float)
    ok = np.isfinite(te["osrm_s"])                               # B2/B3 need a route; same rows for everyone
    y, X = y[ok], X[ok]
    preds = {
        "B1 straight-line / city speed": base.b1(X[:, fi["straight_m"]]),
        "B2 raw OSRM": base.b2(X[:, fi["osrm_s"]]),
        "B3 OSRM dist / hex-hour speed": base.b3_predict(X[:, fi["pickup_lat"]].astype(float), X[:, fi["pickup_lng"]].astype(float),
                                                         X[:, fi["how"]], X[:, fi["osrm_m"]]),
        "Model (LightGBM)": np.expm1(model.predict(X)),
    }
    straight, hour = X[:, fi["straight_m"]], X[:, fi["hour"]]
    airport = (X[:, fi["pickup_airport"]] > 0) | (X[:, fi["dropoff_airport"]] > 0)
    manhattan = in_polygon(X[:, fi["pickup_lat"]], X[:, fi["pickup_lng"]])
    slices = {
        "All June": np.ones(len(y), bool),
        "< 3 km (pickup-like)": straight < 3000, "3-10 km": (straight >= 3000) & (straight < 10000),
        ">= 10 km": straight >= 10000,
        "Manhattan pickup": manhattan, "Outer boroughs": ~manhattan & ~airport, "Airport (either end)": airport,
        "AM peak 7-10": (hour >= 7) & (hour < 10), "Midday 10-16": (hour >= 10) & (hour < 16),
        "PM peak 16-20": (hour >= 16) & (hour < 20), "Night 0-6": hour < 6,
    }
    metrics = {"version": vdir.name, "test_rows": int(len(y)), "slices": {}}
    for sname, m in slices.items():
        metrics["slices"][sname] = {"n": int(m.sum()), **{k: scores(y[m], v[m]) for k, v in preds.items()}}

    allm, short = metrics["slices"]["All June"], metrics["slices"]["< 3 km (pickup-like)"]
    gate = all(s["Model (LightGBM)"]["mae_s"] < min(s["B2 raw OSRM"]["mae_s"], s["B3 OSRM dist / hex-hour speed"]["mae_s"])
               for s in (allm, short))
    metrics["gate_beats_B2_B3_overall_and_short"] = bool(gate)
    (vdir / "metrics.json").write_text(json.dumps(metrics, indent=2))

    names = list(preds)
    head = "| Slice | Trips | " + " | ".join(n.split(" ")[0] if not n.startswith("Model") else "Model" for n in names) + " | Model vs best baseline |"
    rows = [head, "|---|---|" + "---|" * (len(names) + 1)]
    for sname, s in metrics["slices"].items():
        maes = [s[n]["mae_s"] for n in names]
        best_base = min(maes[:3])
        rows.append(f"| {sname} | {s['n']:,} | " + " | ".join(f"{v / 60:.2f}" for v in maes) +
                    f" | {100 * (maes[3] - best_base) / best_base:+.1f}% |")
    imp = list(info["importance_gain"].items())
    total = sum(v for _, v in imp) or 1
    card = f"""# Model card: ETA {vdir.name}

_Generated by `python -m ml.evaluate`. Do not edit by hand._

| | |
|---|---|
| **Question** | How many seconds for a car at A to reach B, leaving now? |
| **Model** | LightGBM regressor on `log1p(duration_s)`, {info['best_iteration']} trees, {info['params']['num_leaves']} leaves |
| **Trained on** | {info['train_rows']:,} trips, Jan–Apr 2016 (seeded sample); early stopping on {info['validate_rows']:,} May trips |
| **Hardware** | `{info['device']}`{' on ' + info['gpu'] if info.get('gpu') else ''}, {info['train_seconds']:.0f} s |
| **Tested on** | {metrics['test_rows']:,} June 2016 trips the model never saw (the replay month) |
| **Gate** | beats B2 and B3 on MAE overall and on < 3 km: **{'PASS' if gate else 'FAIL'}** |
| **Features** | {', '.join(f'`{f}`' for f in info['features'])}; all known at dispatch time |
| **Excluded** | fare, tip, payment type, passenger count, drop-off time (unknown at dispatch, or leak the answer) |

## Mean absolute error by slice (minutes, lower is better)

B1 = straight-line distance / city speed · B2 = raw OSRM · B3 = OSRM distance / historical median speed for the
pickup's res-8 hex and hour of week (all fitted on Jan–Apr only).

{chr(10).join(rows)}

**Overall RMSLE:** model {allm['Model (LightGBM)']['rmsle']:.4f} · B3 {allm['B3 OSRM dist / hex-hour speed']['rmsle']:.4f} · B2 {allm['B2 raw OSRM']['rmsle']:.4f} · B1 {allm['B1 straight-line / city speed']['rmsle']:.4f}.
**p90 absolute error:** model {allm['Model (LightGBM)']['p90_abs_s'] / 60:.1f} min · B3 {allm['B3 OSRM dist / hex-hour speed']['p90_abs_s'] / 60:.1f} min.

## What the model leans on (gain share)

{chr(10).join(f'- `{f}`: {100 * v / total:.1f}%' for f, v in imp[:8])}

## Known limits

- Taxi trips are passenger trips, not empty pickup legs; the < 3 km slice is the closest proxy for pickup drives.
- 2016 traffic, yellow cabs only, Manhattan-heavy (see the data card); outer-borough and airport slices have
  fewer trips and wider error.
- Trained against OSRM's free-flow estimate: if OSRM's road graph changes, retrain.
"""
    (vdir / "card.md").write_text(card, encoding="utf-8")
    (ROOT / "docs" / "model_card_eta.md").write_text(card, encoding="utf-8")
    print(card)


if __name__ == "__main__":
    main()
