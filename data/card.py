"""Generate docs/data_card.md from the download + cleaning manifests and the clean Parquet (spec §5.4).

    python -m data.card

Every number in the card is computed here, so re-running after a re-download or a rule change
keeps the card honest.
"""
from __future__ import annotations

import argparse
import json
from pathlib import Path

import duckdb

from core import config

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / "docs" / "data_card.md"

# Rough Manhattan polygon (lng lat), enough to measure how Manhattan-heavy the data is
MANHATTAN = ("POLYGON((-74.0204 40.6996, -74.0134 40.7516, -73.9318 40.8789, -73.9103 40.8776, "
             "-73.9283 40.7980, -73.9718 40.7096, -74.0204 40.6996))")
AIRPORTS = {"JFK": (40.620, 40.666, -73.835, -73.745), "LGA": (40.764, 40.790, -73.891, -73.854)}


def stats(con, files: list[str]) -> dict:
    airport = " OR ".join(f"(pickup_lat BETWEEN {a} AND {b} AND pickup_lng BETWEEN {c} AND {d})"
                          for a, b, c, d in AIRPORTS.values())
    row = con.execute(f"""
        SELECT count(*),
               quantile_cont(duration_s, [0.5, 0.9]),
               quantile_cont(dist_m, [0.5, 0.9]),
               avg(CASE WHEN dist_m < 3000 THEN 1 ELSE 0 END),
               avg(CASE WHEN ST_Contains(ST_GeomFromText('{MANHATTAN}'), ST_Point(pickup_lng, pickup_lat)) THEN 1 ELSE 0 END),
               avg(CASE WHEN {airport} THEN 1 ELSE 0 END),
               min(pickup_ts), max(pickup_ts)
        FROM read_parquet({files!r})
    """).fetchone()
    return {"rows": row[0], "dur_p50": row[1][0], "dur_p90": row[1][1], "dist_p50": row[2][0], "dist_p90": row[2][1],
            "short_share": row[3], "manhattan_share": row[4], "airport_share": row[5], "first": row[6], "last": row[7]}


def main() -> None:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--data-dir", type=Path, default=config.DATA_DIR)
    a = ap.parse_args()
    raw = json.loads((a.data_dir / "raw" / "manifest.json").read_text())
    clean = json.loads((a.data_dir / "clean" / "manifest.json").read_text())
    months = clean["months"]
    rules = clean["rules"]

    con = duckdb.connect()
    con.execute("INSTALL spatial; LOAD spatial;")
    trips = (a.data_dir / "clean" / "trips").as_posix()
    by_split = {s: stats(con, [f"{trips}/{m}.parquet" for m, v in months.items() if v["split"] == s])
                for s in ("train", "validate", "test")}
    days_ok = all(d["rows"] == d["source_count"] for d in raw["days"].values())

    f = lambda n: f"{n:,}"  # noqa: E731
    lines = [
        "# Data card: NYC 2016 yellow-taxi trips",
        "",
        "_Generated by `python -m data.card` from `raw/manifest.json` and `clean/manifest.json`. Do not edit by hand._",
        "",
        "| | |", "|---|---|",
        f"| **Source** | NYC Open Data, *2016 Yellow Taxi Trip Data* (dataset `uacg-pexx`), via the Socrata API |",
        "| **Licence** | NYC Open Data terms of use (public data, attribution requested) |",
        "| **Period** | 1 Jan – 30 Jun 2016 (the only 2016 months with exact coordinates; TLC Parquet has zone IDs only) |",
        f"| **Raw rows** | {f(raw['total_rows'])} over {len(raw['days'])} days; every day verified against the API's own count: {'yes' if days_ok else 'NO'} |",
        f"| **Clean rows** | {f(sum(m['clean_rows'] for m in months.values()))} "
        f"({sum(m['clean_rows'] for m in months.values()) / raw['total_rows']:.1%} kept) |",
        "| **Columns kept** | pickup/dropoff timestamp and coordinates, metered distance; derived `duration_s`, `dist_m` (straight line) |",
        "| **Dropped on purpose** | fare, tip, payment type, passenger count, vendor: unknown at dispatch time or leak the answer |",
        "",
        "## Splits (by time, never random)",
        "",
        "| Split | Months | Rows | Median trip | p90 trip | Median distance | Trips < 3 km |",
        "|---|---|---|---|---|---|---|",
    ]
    for s, label in (("train", "Jan–Apr"), ("validate", "May"), ("test", "Jun")):
        st = by_split[s]
        lines.append(f"| {s} | {label} | {f(st['rows'])} | {st['dur_p50'] / 60:.1f} min | {st['dur_p90'] / 60:.1f} min | "
                     f"{st['dist_p50'] / 1000:.2f} km | {st['short_share']:.0%} |")
    lines += [
        "",
        "Train fits both models and the B3 speed table; validate drives early stopping and warm-starts the forecaster; "
        "test is the final offline metric **and** the replay month (spec §5.3).",
        "",
        "## Cleaning: rows removed per rule",
        "",
        "Rules run in this order (`data/clean.sql`); each count is rows removed by that rule after the ones above it.",
        "",
        "| Rule | " + " | ".join(months) + " | Total |",
        "|---|" + "---|" * (len(months) + 1),
    ]
    for r in rules:
        vals = [months[m]["removed"][r] for m in months]
        lines.append(f"| `{r}` | " + " | ".join(f(v) for v in vals) + f" | {f(sum(vals))} |")
    lines.append("| **Kept** | " + " | ".join(f"{months[m]['kept_pct']}%" for m in months) + " | |")
    test = by_split["test"]
    lines += [
        "",
        "## Known biases and limits",
        "",
        f"- **Yellow cabs only.** No green cabs, no Uber/Lyft (FHV records have no coordinates). Demand is a taxi view of the city.",
        f"- **Manhattan-heavy.** {test['manhattan_share']:.0%} of June pickups are in Manhattan; outer-borough demand is thin, so "
        "models are least reliable there. Results are reported per slice.",
        f"- **Airports matter.** {test['airport_share']:.1%} of June pickups are at JFK or LGA: long, highway-heavy trips with their own error profile.",
        "- **2016 traffic.** Speeds reflect 2016 (pre-congestion-pricing); fine for a method comparison, not a 2026 forecast.",
        "- **Meter errors survive in small numbers.** Rules remove the impossible, not the merely odd; the ETA target is log-scaled to limit their pull.",
        "- **Straight-line speed check.** Rule 3 uses straight-line distance × 1.3 until OSRM road distances are precomputed.",
        "",
        "## Reproduce",
        "",
        "```bash",
        "python -m data.download   # ~3.5 h, resumable, count-verified per day",
        "python -m data.clean      # ~2 min",
        "python -m data.card",
        "```",
        "",
    ]
    OUT.write_text("\n".join(lines), encoding="utf-8")
    print(f"wrote {OUT.relative_to(ROOT)}")


if __name__ == "__main__":
    main()
